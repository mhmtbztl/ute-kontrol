const check = (ok, name, detail) => ok ? (p++, console.log(`[PASS] ${name}`)) : (f++, console.error(`[FAIL] ${name}\n       ${detail}`));
check(/tenant-assets/.test(sql) && /public[^,)]*false/i.test(sql), 'A1. Logo bucket ozeldir', 'private bucket yok');
