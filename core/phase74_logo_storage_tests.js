const fs = require('fs');
const path = require('path');
const FILE = path.join(__dirname, '..', 'supabase', 'migration_phase74_tenant_logo_storage.sql');
const sql = fs.existsSync(FILE) ? fs.readFileSync(FILE, 'utf8').replace(/\r\n?/g, '\n') : '';
